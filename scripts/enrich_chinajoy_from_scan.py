def existing_names(ws):
    names = set()
    for r in range(2, ws.max_row + 1):
        v = ws.cell(row=r, column=5).value
        if v:
            names.add(str(v).strip())
    return names


def append_exhibitors(ws, rows):
    """追加到参展商名录，按名称去重。"""
    have = existing_names(ws)
    start = ws.max_row + 1
    added = 0
    seq = ws.max_row  # 原最后序号约 = max_row-1，下面用 max
    # 取当前最大序号
    max_seq = 0
    for r in range(2, ws.max_row + 1):
        try:
            max_seq = max(max_seq, int(ws.cell(row=r, column=1).value or 0))
        except Exception:
            pass
    for e in rows:
        name = e[3].strip()
        # 宽松去重：名称完全相同则跳过
        if name in have:
            continue
        # 也跳过明显已有的核心头部简称匹配
        skip = False
        for h in have:
            if name == h or (len(name) >= 4 and name in h and h in name):
                skip = True
                break
        if skip:
            continue
        max_seq += 1
        row = (max_seq,) + e
        r = start + added
        for c, val in enumerate(row, 1):
            cell = ws.cell(row=r, column=c, value=val)
            cell.font = BODY_FONT
            cell.alignment = WRAP
            cell.border = THIN
            cell.fill = SCAN_FILL
        cat = e[0]
        if cat in CAT_COLORS:
            ws.cell(row=r, column=2).fill = PatternFill("solid", fgColor=CAT_COLORS[cat])
        ws.row_dimensions[r].height = 32
        have.add(name)
        added += 1
    # 更新筛选范围
    ws.auto_filter.ref = f"A1:O{ws.max_row}"
    return added


def append_simple(ws, rows):
    start = ws.max_row + 1
    for i, row in enumerate(rows):
        r = start + i
        for c, val in enumerate(row, 1):
            cell = ws.cell(row=r, column=c, value=val)
            cell.font = BODY_FONT
            cell.alignment = WRAP
            cell.border = THIN
            cell.fill = SCAN_FILL
        ws.row_dimensions[r].height = 30
    if ws.auto_filter.ref:
        # expand filter roughly
        ws.auto_filter.ref = f"A1:{get_column_letter(ws.max_column)}{ws.max_row}"
    return len(rows)


def replace_or_create_sheet(wb, title):
    if title in wb.sheetnames:
        idx = wb.sheetnames.index(title)
        del wb[title]
        ws = wb.create_sheet(title, idx)
    else:
        ws = wb.create_sheet(title)
    return ws


