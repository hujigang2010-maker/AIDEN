# ---- 样式 ----
HEADER_FONT = Font(name="WenQuanYi Micro Hei", size=11, bold=True, color="FFFFFF")
TITLE_FONT = Font(name="WenQuanYi Micro Hei", size=14, bold=True)
NORMAL_FONT = Font(name="WenQuanYi Micro Hei", size=10)
HEADER_FILL = PatternFill("solid", fgColor="305496")
SECTION_FILL = PatternFill("solid", fgColor="D9E1F2")
THIN = Side(border_style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
CENTER = Alignment(horizontal="center", vertical="center", wrap_text=True)
LEFT = Alignment(horizontal="left", vertical="center", wrap_text=True)


def add_sheet(name, columns, rows, col_widths=None, title=None):
    ws = wb.create_sheet(name)
    r = 1
    if title:
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=len(columns))
        c = ws.cell(row=r, column=1, value=title)
        c.font = TITLE_FONT
        c.alignment = CENTER
        c.fill = SECTION_FILL
        r += 1
    # header
    for ci, h in enumerate(columns, 1):
        cell = ws.cell(row=r, column=ci, value=h)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = CENTER
        cell.border = BORDER
    r += 1
    # data
    for row in rows:
        if isinstance(row, tuple) and row and row[0] == "__SECTION__":
            ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=len(columns))
            cell = ws.cell(row=r, column=1, value=row[1])
            cell.font = Font(name="WenQuanYi Micro Hei", size=11, bold=True, color="1F4E79")
            cell.fill = SECTION_FILL
            cell.alignment = LEFT
            cell.border = BORDER
            r += 1
            continue
        for ci, v in enumerate(row, 1):
            cell = ws.cell(row=r, column=ci, value=v)
            cell.font = NORMAL_FONT
            cell.alignment = LEFT
            cell.border = BORDER
        r += 1
    # widths
    if col_widths is None:
        col_widths = [16] * len(columns)
    for i, w in enumerate(col_widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A3" if title else "A2"
    return ws


