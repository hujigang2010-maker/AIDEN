def style_title_block(ws, title, subtitle, ncols):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncols)
    ws.cell(row=1, column=1, value=title).font = font_title
    ws.cell(row=1, column=1).fill = fill_navy
    ws.cell(row=1, column=1).alignment = Alignment(horizontal="left",
                                                   vertical="center", indent=1)
    ws.row_dimensions[1].height = 38

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=ncols)
    ws.cell(row=2, column=1, value=subtitle).font = font_sub
