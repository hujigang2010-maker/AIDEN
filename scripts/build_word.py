def set_cell_bg(cell, color):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color)
    tc_pr.append(shd)


def add_title(text, level=1):
    sizes = {1: 22, 2: 16, 3: 13}
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT if level > 1 else WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(sizes.get(level, 12))
    run.font.name = "WenQuanYi Micro Hei"
    run.element.rPr.rFonts.set(qn("w:eastAsia"), "WenQuanYi Micro Hei")
    if level == 1:
        run.font.color.rgb = RGBColor(0x1F, 0x4E, 0x79)


def add_para(text, bold=False, size=10.5, color=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = "WenQuanYi Micro Hei"
    run.element.rPr.rFonts.set(qn("w:eastAsia"), "WenQuanYi Micro Hei")
    if color:
        run.font.color.rgb = RGBColor(*color)


def add_table(headers, rows, widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Light Grid Accent 1"
    table.autofit = False
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = h
        set_cell_bg(cell, "305496")
        for p in cell.paragraphs:
            for r in p.runs:
                r.bold = True
                r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
                r.font.size = Pt(10)
                r.font.name = "WenQuanYi Micro Hei"
                r.element.rPr.rFonts.set(qn("w:eastAsia"), "WenQuanYi Micro Hei")
    for ri, row in enumerate(rows, 1):
        for ci, val in enumerate(row):
            cell = table.rows[ri].cells[ci]
            cell.text = str(val) if val is not None else ""
            for p in cell.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(9.5)
                    r.font.name = "WenQuanYi Micro Hei"
                    r.element.rPr.rFonts.set(qn("w:eastAsia"), "WenQuanYi Micro Hei")
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
    if widths:
        for i, w in enumerate(widths):
            for row in table.rows:
                row.cells[i].width = Cm(w)
    doc.add_paragraph()


