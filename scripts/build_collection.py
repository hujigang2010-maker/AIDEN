def thin():
    s = Side(style="thin", color="D0D7DE")
    return Border(left=s, right=s, top=s, bottom=s)


def widths(ws, arr):
    for i, w in enumerate(arr, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def title(ws, span, text, sub):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=span)
    c = ws.cell(1, 1, text)
    c.font = Font(name="微软雅黑", size=16, bold=True, color=WHITE)
    c.fill = PatternFill("solid", fgColor=PRIMARY)
    c.alignment = Alignment(vertical="center", wrap_text=True)
    ws.row_dimensions[1].height = 34
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=span)
    c2 = ws.cell(2, 1, sub)
    c2.font = Font(name="微软雅黑", size=10, italic=True, color=GREY)
    c2.fill = PatternFill("solid", fgColor=LIGHT)
    c2.alignment = Alignment(vertical="center", wrap_text=True)
    ws.row_dimensions[2].height = 32


def headers(ws, row, cols, fill=PRIMARY):
    for i, h in enumerate(cols, 1):
        c = ws.cell(row, i, h)
        c.font = Font(name="微软雅黑", size=11, bold=True, color=WHITE)
        c.fill = PatternFill("solid", fgColor=fill)
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = thin()
    ws.row_dimensions[row].height = 28


def rows(ws, start, data):
    for i, row in enumerate(data):
        for j, v in enumerate(row, 1):
            c = ws.cell(start + i, j, v)
            c.font = Font(name="微软雅黑", size=10, color=DARK)
            c.alignment = Alignment(vertical="center", wrap_text=True)
            c.fill = PatternFill("solid", fgColor=ALT if i % 2 else WHITE)
            c.border = thin()
        ws.row_dimensions[start + i].height = 38


def sheet(wb, name, span, t, sub, cols, data, w, fill=PRIMARY):
    ws = wb.create_sheet(name) if wb.sheetnames != ["Sheet"] else wb.active
    if ws.title == "Sheet":
        ws.title = name
    title(ws, span, t, sub)
    headers(ws, 3, cols, fill)
    rows(ws, 4, data)
    widths(ws, w)
    ws.freeze_panes = "A4"
    return ws


