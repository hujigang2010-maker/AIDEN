def _apply_table(ws, section: dict) -> None:
    headers = section["headers"]
    rows = section["rows"]
    widths = section["widths"]
    ncol = len(headers)

    ws.sheet_view.showGridLines = False
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = ws.PAPERSIZE_A3
    ws.page_setup.fitToPage = True
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.page_setup.horizontalCentered = True
    ws.page_margins = PageMargins(left=0.4, right=0.4, top=0.6, bottom=0.5, header=0.2, footer=0.2)
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.oddHeader.left.text = "专业技术资格评审申报表"
    ws.oddFooter.right.text = "第 &P 页"
    ws.print_title_rows = "1:3"
    ws.auto_filter.ref = f"A3:{get_column_letter(ncol)}{3 + len(rows)}"
    ws.freeze_panes = "A4"
    ws.sheet_view.zoomScale = 110

    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncol)
    title_cell = ws.cell(1, 1, section["title"])
    title_cell.font = TITLE_FONT
    title_cell.alignment = Alignment(vertical="center", horizontal="left")
    ws.row_dimensions[1].height = 26

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=ncol)
    note_cell = ws.cell(2, 1, section["note"])
    note_cell.font = NOTE_FONT
    note_cell.alignment = Alignment(wrap_text=True, vertical="center")
    ws.row_dimensions[2].height = 32

    for col, header in enumerate(headers, start=1):
        cell = ws.cell(3, col, header)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = THIN
    ws.row_dimensions[3].height = 22

    for r_index, row in enumerate(rows):
        excel_row = 4 + r_index
        warn = any("待核查" in str(value) for value in row)
        for c_index, value in enumerate(row, start=1):
            cell = ws.cell(excel_row, c_index, value)
            cell.font = CELL_FONT
            cell.alignment = WRAP
            cell.border = THIN
            if warn:
                cell.fill = WARN_FILL
            elif r_index % 2 == 1:
                cell.fill = ALT_FILL
        longest = max(len(str(value)) for value in row)
        ws.row_dimensions[excel_row].height = 18 if longest < 24 else min(72, 18 + longest // 18 * 8)

    for col, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(col)].width = width
    ws.auto_filter.ref = f"A3:{get_column_letter(ncol)}{3 + len(rows)}"
    ws.oddHeader.center.text = ""


def write_xlsx(path: Path) -> None:
    wb = Workbook()
    default = wb.active
    wb.remove(default)
    for section in sections():
        ws = wb.create_sheet(section["title"])
        _apply_table(ws, section)
    wb.properties.title = "专业技术资格评审申报表"
    wb.properties.creator = "申报表整理"
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)


