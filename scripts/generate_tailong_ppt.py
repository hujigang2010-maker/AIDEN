def _font(run, size, color, bold=False):
    run.font.size = Pt(size)
    run.font.color.rgb = color
    run.font.bold = bold
    run.font.name = FONT
    rPr = run._r.get_or_add_rPr()
    for tag in ("a:latin", "a:ea", "a:cs"):
        el = rPr.find(qn(tag))
        if el is None:
            el = rPr.makeelement(qn(tag), {})
            rPr.append(el)
        el.set("typeface", FONT)


def slide(bg=INK):
    s = prs.slides.add_slide(BLANK)
    r = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, SW, SH)
    r.fill.solid()
    r.fill.fore_color.rgb = bg
    r.line.fill.background()
    r.shadow.inherit = False
    return s


def rect(s, x, y, w, h, color, shape=MSO_SHAPE.RECTANGLE, line=None):
    sp = s.shapes.add_shape(shape, x, y, w, h)
    sp.fill.solid()
    sp.fill.fore_color.rgb = color
    if line:
        sp.line.color.rgb = line
        sp.line.width = Pt(1.1)
    else:
        sp.line.fill.background()
    sp.shadow.inherit = False
    return sp


def rrect(s, x, y, w, h, color, line=None, adj=0.08):
    sp = rect(s, x, y, w, h, color, MSO_SHAPE.ROUNDED_RECTANGLE, line)
    try:
        sp.adjustments[0] = adj
    except Exception:
        pass
    return sp


def txt(s, x, y, w, h, lines, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP):
    tb = s.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = Pt(2)
    tf.margin_right = Pt(2)
    tf.margin_top = Pt(2)
    tf.margin_bottom = Pt(2)
    for i, spec in enumerate(lines):
        text, size, color, bold = spec[0], spec[1], spec[2], spec[3]
        space_after = spec[4] if len(spec) > 4 else 4
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.space_after = Pt(space_after)
        run = p.add_run()
        run.text = text
        _font(run, size, color, bold)
    return tb


def header(s, title, subtitle=None, tag=None):
    rect(s, Inches(0), Inches(0), Inches(0.14), SH, AMBER)
    txt(s, Inches(0.45), Inches(0.24), Inches(10.6), Inches(0.5),
        [(title, 24, WHITE, True)])
    if subtitle:
        txt(s, Inches(0.47), Inches(0.72), Inches(10.6), Inches(0.32),
            [(subtitle, 12, AMBER_LT, False)])
    if tag:
        chip = rrect(s, Inches(11.2), Inches(0.28), Inches(1.8), Inches(0.4), TEAL, AMBER)
        tf = chip.text_frame
        tf.word_wrap = False
        p = tf.paragraphs[0]
        p.alignment = PP_ALIGN.CENTER
        r = p.add_run()
        r.text = tag
        _font(r, 11, AMBER_LT, True)
    rect(s, Inches(0.45), Inches(1.12), Inches(12.4), Pt(1.4), AMBER)


def footer(s, n):
    txt(s, Inches(0.45), Inches(7.1), Inches(10.5), Inches(0.28),
        [(FOOTER, 9, MUTED, False)])
    txt(s, Inches(11.9), Inches(7.1), Inches(1.1), Inches(0.28),
        [(str(n), 9, MUTED, False)], align=PP_ALIGN.RIGHT)


def new(title=None, subtitle=None, tag=None):
    global PAGE
    PAGE += 1
    s = slide()
    if title:
        header(s, title, subtitle, tag)
    footer(s, PAGE)
    return s


def card(s, x, y, w, h, title, bullets, accent=AMBER, body_size=12):
    rrect(s, x, y, w, h, TEAL)
    rect(s, x, y, Inches(0.09), h, accent)
    txt(s, x + Inches(0.2), y + Inches(0.12), w - Inches(0.35), Inches(0.36),
        [(title, 13, AMBER_LT, True)])
    lines = [("• " + b, body_size, OFF, False, 3) for b in bullets]
    txt(s, x + Inches(0.2), y + Inches(0.5), w - Inches(0.35), h - Inches(0.62), lines)


def draw_table(s, x0, y0, col_widths_in, row_h_in, headers, rows,
               header_bg=AMBER, header_fg=INK, zebra=(TEAL, INK_2),
               first_col_color=AMBER_LT, body_size=11, header_size=11,
               gap_in=0.05):
    widths = [Inches(w) for w in col_widths_in]
    xs = [x0]
    for w in widths[:-1]:
        xs.append(xs[-1] + w)
    gap = Inches(gap_in)
    row_h = Inches(row_h_in)
    for j, h in enumerate(headers):
        rrect(s, xs[j], y0, widths[j] - gap, row_h, header_bg)
        txt(s, xs[j] + Inches(0.06), y0, widths[j] - gap - Inches(0.1), row_h,
            [(h, header_size, header_fg, True)],
            align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)
    for i, row in enumerate(rows):
        y = y0 + row_h + Inches(0.05) + i * (row_h + Inches(0.04))
        bg = zebra[0] if i % 2 == 0 else zebra[1]
        for j, val in enumerate(row):
            rrect(s, xs[j], y, widths[j] - gap, row_h, bg)
            color = first_col_color if j == 0 else WHITE
            txt(s, xs[j] + Inches(0.08), y, widths[j] - gap - Inches(0.12), row_h,
                [(str(val), body_size, color, j == 0)],
                align=PP_ALIGN.CENTER if j else PP_ALIGN.LEFT,
                anchor=MSO_ANCHOR.MIDDLE)


