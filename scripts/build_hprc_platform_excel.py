def consul_row(i, country, typ, opened, district, area):
    known = KNOWN_CONSULS.get(country)
    if known:
        name_zh, name_en, source = known
        search = f"检索关键词：「{country}驻上海总领事 {name_zh}」"
        note = f"公开信息参考：{source}；任职以各馆官网及外办确认为准"
    else:
        name_zh = "（请公开检索现任馆长）"
        name_en = "—"
        search = f"检索关键词：「{country}驻上海总领事」或「{country}驻沪总领事馆 馆长」"
        note = "平台仅提供检索线索，不收录电话/邮箱/微信"
    return [
        i,
        country,
        typ,
        opened,
        district,
        area,
        name_zh,
        name_en,
        search,
        note,
    ]


