def build_stats(ws):
    """统计透视，方便招商汇报。"""
    from collections import Counter

    ws["A1"] = "名录统计（基于本表已录入条目）"
    ws["A1"].font = TITLE_FONT
    headers = ["参展分类", "已录入条数", "其中头部", "其中中大型/中型", "其中小型/中小/集合"]
    for c, h in enumerate(headers, 1):
        ws.cell(row=3, column=c, value=h)
    style_header(ws, 3, len(headers))

    by_cat = Counter(e[0] for e in EXHIBITORS)
    head = Counter(e[0] for e in EXHIBITORS if e[4] == "头部")
    mid = Counter(e[0] for e in EXHIBITORS if e[4] in ("中大型", "中型", "中小型"))
    small = Counter(e[0] for e in EXHIBITORS if e[4] in ("小型", "小型集合", "集合", "展团", "展团集合", "官方赛事", "展区", "活动集合", "产业会议"))

    r = 4
    for cat, *_rest in CATEGORIES:
        ws.cell(row=r, column=1, value=cat)
        ws.cell(row=r, column=2, value=by_cat.get(cat, 0))
        ws.cell(row=r, column=3, value=head.get(cat, 0))
        ws.cell(row=r, column=4, value=mid.get(cat, 0))
        # 其余算入小/集合等
        rest = by_cat.get(cat, 0) - head.get(cat, 0) - mid.get(cat, 0)
        ws.cell(row=r, column=5, value=rest)
        for c in range(1, 6):
            ws.cell(row=r, column=c).font = BODY_FONT
            ws.cell(row=r, column=c).border = THIN
            if c == 1 and cat in CAT_COLORS:
                ws.cell(row=r, column=c).fill = PatternFill("solid", fgColor=CAT_COLORS[cat])
        r += 1

    # 额外分类
    extra_cats = sorted(set(by_cat) - {c[0] for c in CATEGORIES})
    for cat in extra_cats:
        ws.cell(row=r, column=1, value=cat)
        ws.cell(row=r, column=2, value=by_cat[cat])
        ws.cell(row=r, column=3, value=head.get(cat, 0))
        ws.cell(row=r, column=4, value=mid.get(cat, 0))
        rest = by_cat[cat] - head.get(cat, 0) - mid.get(cat, 0)
        ws.cell(row=r, column=5, value=rest)
        for c in range(1, 6):
            ws.cell(row=r, column=c).font = BODY_FONT
            ws.cell(row=r, column=c).border = THIN
        r += 1

    ws.cell(row=r + 1, column=1, value="本表参展商条目合计").font = Font(name="微软雅黑", bold=True)
    ws.cell(row=r + 1, column=2, value=len(EXHIBITORS)).font = Font(name="微软雅黑", bold=True)
    ws.cell(row=r + 3, column=1, value="使用提示").font = SECTION_FONT
    ws.cell(
        row=r + 4,
        column=1,
        value="筛选「规模层级」含小型/中小型/集合，可快速查看中小参展商与团队池；筛选「招商价值标签」可按赛道组局。",
    )
    ws.merge_cells(start_row=r + 4, start_column=1, end_row=r + 4, end_column=5)
    autofit(ws, [18, 14, 12, 18, 22])


