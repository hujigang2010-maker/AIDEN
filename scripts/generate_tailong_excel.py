ZEBRA_FILL = PatternFill("solid", fgColor=ZEBRA)
OK_FILL = PatternFill("solid", fgColor=OK)
WARN_FILL = PatternFill("solid", fgColor=WARN)
RED_FILL = PatternFill("solid", fgColor=RED_SOFT)
WRAP = Alignment(wrap_text=True, vertical="center")
CENTER = Alignment(horizontal="center", vertical="center", wrap_text=True)

wb = Workbook()


def style_sheet(ws, title, headers, rows, widths, note=None, status_col=None, row_height=34):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    c = ws.cell(1, 1, title)
    c.font = TITLE_FONT
    c.fill = LIGHT_FILL
    c.alignment = Alignment(vertical="center", wrap_text=True)
    ws.row_dimensions[1].height = 34

    for j, h in enumerate(headers, 1):
        cell = ws.cell(2, j, h)
        cell.font = HEAD_FONT
        cell.fill = HEAD_FILL
        cell.alignment = CENTER
        cell.border = BORDER
    ws.row_dimensions[2].height = 26

    for i, row in enumerate(rows, 3):
        for j, v in enumerate(row, 1):
            cell = ws.cell(i, j, v)
            cell.font = BODY_FONT
            cell.alignment = WRAP
            cell.border = BORDER
            if (i - 3) % 2 == 1:
                cell.fill = ZEBRA_FILL
            if status_col and j == status_col and isinstance(v, str):
                if any(k in v for k in ("已完成", "进行中", "P0", "必须", "已确认")):
                    cell.fill = OK_FILL
                elif any(k in v for k in ("待启动", "待确认", "P1", "观察", "可选")):
                    cell.fill = WARN_FILL
                elif any(k in v for k in ("逾期", "高", "红线", "禁止")):
                    cell.fill = RED_FILL
        ws.row_dimensions[i].height = row_height

    for j, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(j)].width = w

    if note:
        r = len(rows) + 4
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=len(headers))
        c = ws.cell(r, 1, note)
        c.font = Font(name=FONT, size=10, italic=True, color=MUTED)
        c.alignment = WRAP
        ws.row_dimensions[r].height = 48
    ws.freeze_panes = "A3"


