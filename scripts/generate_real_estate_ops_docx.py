def bullets(doc, items, *, size=11.5):
    for item in items:
        p = doc.add_paragraph()
        _set_spacing(p, before=0, after=3, line=1.28)
        p.paragraph_format.left_indent = Cm(0.75)
        p.paragraph_format.first_line_indent = Cm(-0.4)
        run = p.add_run("•  " + item)
        set_run_font(run, size=size, color=INK, name_cn="宋体")


def numbered(doc, items, *, size=11.5):
    for i, item in enumerate(items, 1):
        p = doc.add_paragraph()
        _set_spacing(p, before=0, after=3, line=1.28)
        p.paragraph_format.left_indent = Cm(0.75)
        p.paragraph_format.first_line_indent = Cm(-0.45)
        run = p.add_run(f"{i}.  {item}")
        set_run_font(run, size=size, color=INK, name_cn="宋体")


def shade_cell(cell, fill_hex):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill_hex)
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    tcPr.append(shd)


def set_cell_border(cell, **kwargs):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcBorders = tcPr.find(qn("w:tcBorders"))
    if tcBorders is None:
        tcBorders = OxmlElement("w:tcBorders")
        tcPr.append(tcBorders)
    for edge in ("top", "left", "bottom", "right"):
        el = tcBorders.find(qn(f"w:{edge}"))
        if el is None:
            el = OxmlElement(f"w:{edge}")
            tcBorders.append(el)
        for k, v in kwargs.items():
            el.set(qn(f"w:{k}"), v)


def set_cell_text(cell, text, *, bold=False, size=9.5, color=INK, name_cn="宋体", align=None, fill=None):
    cell.text = ""
    p = cell.paragraphs[0]
    _set_spacing(p, before=2, after=2, line=1.15, align=align)
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, color=color, name_cn=name_cn)
    if fill:
        shade_cell(cell, fill)
    set_cell_border(cell, val="single", sz="4", color="C5CDD6", space="0")


def add_table(doc, headers, rows, *, col_widths=None, header_fill="1B365D"):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    for i, h in enumerate(headers):
        set_cell_text(table.rows[0].cells[i], h, bold=True, size=9.5, color=WHITE, name_cn="黑体", align=WD_ALIGN_PARAGRAPH.CENTER, fill=header_fill)
    for r_i, row in enumerate(rows):
        fill = "F4F1EA" if r_i % 2 == 0 else "FFFFFF"
        for c_i, val in enumerate(row):
            align = WD_ALIGN_PARAGRAPH.LEFT if c_i == 0 else WD_ALIGN_PARAGRAPH.LEFT
            set_cell_text(table.rows[r_i + 1].cells[c_i], val, size=9, fill=fill, align=align)
    if col_widths:
        for row in table.rows:
            for idx, w in enumerate(col_widths):
                row.cells[idx].width = Cm(w)
    cap = doc.add_paragraph()
    _set_spacing(cap, before=2, after=10)
    return table


def callout(doc, title, text, *, fill="F4F1EA", bar="8C6A2F"):
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.cell(0, 0)
    shade_cell(cell, fill)
    set_cell_border(cell, val="single", sz="4", color=bar, space="0")
    cell.text = ""
    p1 = cell.paragraphs[0]
    _set_spacing(p1, before=4, after=2, line=1.2)
    run = p1.add_run(title)
    set_run_font(run, size=10.5, bold=True, color=NAVY, name_cn="黑体", name_en="Arial")
    p2 = cell.add_paragraph()
    _set_spacing(p2, before=0, after=4, line=1.25)
    run = p2.add_run(text)
    set_run_font(run, size=10.5, color=INK, name_cn="宋体")
    sp = doc.add_paragraph()
    _set_spacing(sp, after=8)


def add_page_number(paragraph):
    run1 = paragraph.add_run("第 ")
    set_run_font(run1, size=9, color=MUTED, name_cn="宋体")
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld_sep = OxmlElement("w:fldChar")
    fld_sep.set(qn("w:fldCharType"), "separate")
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")
    r2 = paragraph.add_run()
    r2._r.append(fld_begin)
    r2._r.append(instr)
    r2._r.append(fld_sep)
    t = OxmlElement("w:t")
    t.text = "1"
    r2._r.append(t)
    r2._r.append(fld_end)
    set_run_font(r2, size=9, color=MUTED, name_cn="宋体")
    run3 = paragraph.add_run(" 页")
    set_run_font(run3, size=9, color=MUTED, name_cn="宋体")


