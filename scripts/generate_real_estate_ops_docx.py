def set_run_font(run, *, size=12, bold=False, color=None, name_cn="宋体", name_en="Times New Roman", italic=False):
    run.font.name = name_en
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), name_en)
    rfonts.set(qn("w:hAnsi"), name_en)
    rfonts.set(qn("w:eastAsia"), name_cn)
    rfonts.set(qn("w:cs"), name_en)


def _set_spacing(p, *, before=0, after=8, line=1.32, align=None):
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    if align is not None:
        p.alignment = align


def add_text(doc, text, *, size=12, bold=False, color=INK, name_cn="宋体", name_en="Times New Roman", before=0, after=8, align=None, first_line=None, italic=False):
    p = doc.add_paragraph()
    _set_spacing(p, before=before, after=after, align=align)
    if first_line is not None:
        p.paragraph_format.first_line_indent = Cm(first_line)
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, color=color, name_cn=name_cn, name_en=name_en, italic=italic)
    return p


def add_rich_para(doc, segments, *, before=0, after=8, first_line=0.74, align=None, line=1.32):
    """segments: list of (text, kwargs)."""
    p = doc.add_paragraph()
    _set_spacing(p, before=before, after=after, line=line, align=align)
    if first_line:
        p.paragraph_format.first_line_indent = Cm(first_line)
    for text, kwargs in segments:
        run = p.add_run(text)
        set_run_font(run, **kwargs)
    return p


def body(doc, text, *, after=8):
    return add_text(doc, text, size=12, first_line=0.74, after=after)


