def style_sheet(ws, title, headers, rows, widths, note=None, status_col=None, row_height=34):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    c = ws.cell(1, 1, title)
    c.font = TITLE_FONT
    c.fill = LIGHT_FILL
    c.alignment = Alignment(vertical="center", wrap_text=True)
    ws.row_dimensions[1].height = 34

    for j, h in enumerate(headers, 1):
        cell = ws.cell(2, j, h)
        cell.font = HEAD_FONT
        cell.fill = HEAD_FILL
        cell.alignment = CENTER
        cell.border = BORDER
    ws.row_dimensions[2].height = 26

    for i, row in enumerate(rows, 3):
        for j, v in enumerate(row, 1):
            cell = ws.cell(i, j, v)
            cell.font = BODY_FONT
            cell.alignment = WRAP
            cell.border = BORDER
            if (i - 3) % 2 == 1:
                cell.fill = ZEBRA_FILL
            if status_col and j == status_col and isinstance(v, str):
                if any(k in v for k in ("完成", "通过", "P0", "启动", "绿灯", "建议同意", "强烈")):
                    cell.fill = OK_FILL
                elif any(k in v for k in ("进行中", "待确认", "P1", "观察", "黄灯", "建议讨论")):
                    cell.fill = WARN_FILL
                elif any(k in v for k in ("未启动", "阻断", "红灯", "止损", "禁止", "高风险")):
                    cell.fill = RISK_FILL
        ws.row_dimensions[i].height = row_height

    for j, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(j)].width = w

    if note:
        r = len(rows) + 4
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=len(headers))
        c = ws.cell(r, 1, note)
        c.font = NOTE_FONT
        c.alignment = WRAP
        ws.row_dimensions[r].height = 42
    ws.freeze_panes = "A3"
    return ws


def add_status_validation(ws, col_letter, start_row, end_row, options='"未启动,进行中,已完成,阻断,观察"'):
    dv = DataValidation(type="list", formula1=options, allow_blank=True)
    dv.error = "请选择列表中的状态"
    dv.errorTitle = "状态无效"
    ws.add_data_validation(dv)
    dv.add(f"{col_letter}{start_row}:{col_letter}{end_row}")


