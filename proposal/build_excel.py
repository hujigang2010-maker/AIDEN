HERE = os.path.dirname(os.path.abspath(__file__))
FONT = "Microsoft YaHei"

wb = Workbook()
HEAD_FILL = PatternFill("solid", fgColor="16213F")
TITLE_FILL = PatternFill("solid", fgColor="0B1020")
ALT_FILL = PatternFill("solid", fgColor="F2F5FC")
thin = Side(style="thin", color="C9D4EC")
BORDER = Border(left=thin, right=thin, top=thin, bottom=thin)
WHITE = Font(name=FONT, color="FFFFFF", bold=True, size=11)
TITLEF = Font(name=FONT, color="FFFFFF", bold=True, size=14)
NORM = Font(name=FONT, size=10.5)
WRAP = Alignment(wrap_text=True, vertical="center")
CEN = Alignment(horizontal="center", vertical="center", wrap_text=True)


def sheet(name, title, headers, rows, widths, title_span=None, first_bold=True, rowh=30):
    ws = wb.create_sheet(name)
    ncol = len(headers); span = title_span or ncol
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=span)
    c = ws.cell(1, 1, title); c.font = TITLEF; c.fill = TITLE_FILL
    c.alignment = Alignment(vertical="center", horizontal="left", indent=1)
    ws.row_dimensions[1].height = 32
    for j, h in enumerate(headers, 1):
        cc = ws.cell(2, j, h); cc.font = WHITE; cc.fill = HEAD_FILL; cc.alignment = CEN; cc.border = BORDER
    ws.row_dimensions[2].height = 24
    for i, row in enumerate(rows, 3):
        for j, val in enumerate(row, 1):
            cc = ws.cell(i, j, val); cc.font = (Font(name=FONT, size=10.5, bold=True) if (first_bold and j == 1) else NORM)
            cc.alignment = WRAP; cc.border = BORDER
            if i % 2 == 1:
                cc.fill = ALT_FILL
        ws.row_dimensions[i].height = rowh
    for j, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(j)].width = w
    ws.sheet_view.showGridLines = False
    ws.freeze_panes = "A3"
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1; ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr = PageSetupProperties(fitToPage=True)
    ws.print_options.horizontalCentered = True
    ws.page_margins.left = ws.page_margins.right = 0.3
    ws.page_margins.top = ws.page_margins.bottom = 0.4
    return ws


