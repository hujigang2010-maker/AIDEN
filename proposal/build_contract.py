def _set_run_font(run, font_name: str, size: float, bold: bool = False) -> None:
    run.font.name = font_name
    run.font.size = Pt(size)
    run.bold = bold
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), font_name)
    rfonts.set(qn("w:ascii"), font_name)
    rfonts.set(qn("w:hAnsi"), font_name)
    rfonts.set(qn("w:cs"), font_name)


def p(
    doc,
    text="",
    *,
    font=CHINESE_FONT,
    size=12,
    bold=False,
    align=WD_ALIGN_PARAGRAPH.LEFT,
    first_indent=None,
    space_after=6,
    space_before=0,
    line_spacing=1.5,
):
    para = doc.add_paragraph()
    para.alignment = align
    pf = para.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    pf.line_spacing = line_spacing
    if first_indent is not None:
        pf.first_line_indent = Cm(first_indent)
    if text:
        run = para.add_run(text)
        _set_run_font(run, font, size, bold=bold)
    return para


def rich(doc, segments, *, size=12, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_indent=0.74, space_after=6):
    para = doc.add_paragraph()
    para.alignment = align
    pf = para.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.5
    if first_indent is not None:
        pf.first_line_indent = Cm(first_indent)
    for text, bold in segments:
        run = para.add_run(text)
        _set_run_font(run, CHINESE_FONT, size, bold=bold)
    return para


